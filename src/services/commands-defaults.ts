/**
 * 获取默认 Command 内容
 * @param commandName 命令名称
 * @returns 默认内容，如果不存在返回 null
 */
export function getDefaultCommand(commandName: string): string | null {
  return DEFAULT_COMMANDS[commandName] || null;
}

/**
 * 获取所有默认 Command 名称列表
 * @returns 命令名称数组
 */
export function getDefaultCommandNames(): string[] {
  return Object.keys(DEFAULT_COMMANDS);
}
